import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const agent = JSON.parse(readFileSync(new URL("docs/agent-openapi.json", root)));
const browser = JSON.parse(readFileSync(new URL("docs/browser-openapi.json", root)));
const request = (p, m = "post") => agent.paths[p][m].requestBody.content["application/json"].schema;
const response = (p, m = "get") => Object.values(agent.paths[p][m].responses).find(r => r.content?.["application/json"] && !r.description?.toLowerCase().includes("error"))?.content["application/json"].schema;
const schemas = {
  agentArgs: request("/v1/automation/run-async"),
  agentSubmitted: response("/v1/automation/run-async", "post"),
  agentRun: response("/v1/runs/{id}"),
  agentCancelled: response("/v1/runs/{id}/cancel", "post"),
  browserArgs: browser.paths["/"].post.requestBody.content["application/json"].schema,
  browserSession: browser.paths["/"].post.responses[201].content["application/json"].schema,
  profileCreateArgs: request("/v1/profiles"),
  profileUpdateArgs: request("/v1/profiles/{profileId}", "patch"),
  profile: response("/v1/profiles", "post"),
  profilesResponse: response("/v1/profiles"),
  profileDetails: response("/v1/profiles/{profileId}"),
  profileSetupArgs: request("/v1/profiles/{profileId}/setup-session"),
  profileSetup: response("/v1/profiles/{profileId}/setup-session", "post"),
  profileSaveArgs: request("/v1/profiles/{profileId}/save"),
  profileSaved: response("/v1/profiles/{profileId}/save", "post"),
};
// The component owns job submission and reconciliation; callers cannot inject webhooks.
delete schemas.agentArgs.properties.webhook_url;
function kind(s) {
  if (!s) throw new Error("Missing contract schema");
  if (s.enum) return { type: "union", value: s.enum.map(value => value === null ? {type:"null"} : {type:"literal",value}) };
  if (s.anyOf || s.oneOf) return {type:"union",value:(s.anyOf ?? s.oneOf).map(shape)};
  switch (s.type) {
    case "string": case "boolean": return {type:s.type};
    case "integer": case "number": return {type:"number"};
    case "array": return {type:"array",value:shape(s.items)};
    case "object": return s.properties && Object.keys(s.properties).length ? {type:"object",value:Object.fromEntries(Object.entries(s.properties).map(([k,v])=>[k,{fieldType:shape(v),optional:!s.required?.includes(k)}]))} : {type:"record",keys:{type:"string"},values:{fieldType:{type:"any"},optional:false}};
    default: return {type:"any"};
  }
}
function shape(s) { const result=kind(s); return s.nullable && !s.enum?.includes(null) ? {type:"union",value:[result,{type:"null"}]} : result; }
function validator(s) {
  switch(s.type) {
    case "any": return "v.any()";
    case "null": return "v.null()";
    case "string": case "boolean": case "number": return `v.${s.type}()`;
    case "literal": return `v.literal(${JSON.stringify(s.value)})`;
    case "union": return `v.union(${s.value.map(validator).join(", ")})`;
    case "array": return `v.array(${validator(s.value)})`;
    case "record": return "v.record(v.string(), v.any())";
    case "object": return `v.object({${Object.entries(s.value).map(([k,f])=>`${JSON.stringify(k)}: ${f.optional ? `v.optional(${validator(f.fieldType)})` : validator(f.fieldType)}`).join(",\n")}})`;
  }
}
writeFileSync(new URL("src/agent_validators.ts", root), '// Generated from the checked-in TinyFish Agent and Browser OpenAPI contracts.\nimport { v } from "convex/values";\n'+Object.entries(schemas).map(([n,s])=>`export const ${n} = ${validator(shape(s))};\n`).join(""));
writeFileSync(new URL("src/component/lib/agent_shapes.ts", root), '// Generated by scripts/generate-agent-contract.mjs.\nimport type { ValidatorJSON } from "convex/values";\n'+Object.entries(schemas).filter(([n])=>!n.endsWith("Args")).map(([n,s])=>`export const ${n}Shape: ValidatorJSON = ${JSON.stringify(shape(s))};\n`).join(""));
writeFileSync(new URL("src/component/lib/agent_constraints.ts", root), '// Generated request constraints.\nexport const constraints = '+JSON.stringify(Object.fromEntries(Object.entries(schemas).filter(([n])=>n.endsWith("Args"))))+' as const;\n');
console.log("Generated Agent, Browser and Profile contracts.");
