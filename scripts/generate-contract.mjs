import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(`docs/${name}-openapi.json`, root), "utf8"));
const search = read("search").paths["/"].get;
const fetch = read("fetch").paths["/"].post;
const searchArgs = { type: "object", properties: Object.fromEntries(search.parameters.map(p => [p.name, { ...p.schema }])), required: search.parameters.filter(p => p.required).map(p => p.name) };
// Null is equivalent to omission upstream; expose the clearer optional number API.
delete searchArgs.properties.page.nullable;
const contracts = { searchArgs, fetchArgs: fetch.requestBody.content["application/json"].schema, searchResponse: search.responses[200].content["application/json"].schema, fetchResponse: fetch.responses[200].content["application/json"].schema };
function validator(s) {
  if (s.anyOf) return "v.union(v.string(), v.record(v.string(), v.any()), v.null())"; // Document tree has an opaque object shape.
  let result;
  if (s.enum) result = `v.union(${s.enum.map(e => `v.literal(${JSON.stringify(e)})`).join(", ")})`;
  else switch (s.type) {
    case "string": result = "v.string()"; break;
    case "integer": case "number": result = "v.number()"; break;
    case "boolean": result = "v.boolean()"; break;
    case "array": result = `v.array(${validator(s.items)})`; break;
    case "object": result = s.properties ? `v.object({\n${Object.entries(s.properties).map(([k, v]) => `  ${k}: ${s.required?.includes(k) ? validator(v) : `v.optional(${validator(v)})`},\n`).join("")}})` : "v.record(v.string(), v.any())"; break;
    default: return "v.any()";
  }
  return s.nullable ? `v.union(${result}, v.null())` : result;
}
function shape(s) {
  if (s.anyOf) return { type: "union", value: [{ type: "string" }, { type: "record", keys: { type: "string" }, values: { fieldType: { type: "any" }, optional: false } }, { type: "null" }] };
  let result;
  if (s.enum) result = { type: "union", value: s.enum.map(value => ({ type: "literal", value })) };
  else switch (s.type) {
    case "string": case "boolean": result = { type: s.type }; break;
    case "integer": case "number": result = { type: "number" }; break;
    case "array": result = { type: "array", value: shape(s.items) }; break;
    case "object": result = s.properties ? { type: "object", value: Object.fromEntries(Object.entries(s.properties).map(([k,v]) => [k, { fieldType: shape(v), optional: !s.required?.includes(k) }])) } : { type: "record", keys: { type: "string" }, values: { fieldType: { type: "any" }, optional: false } }; break;
    default: return { type: "any" };
  }
  return s.nullable ? { type: "union", value: [result, { type: "null" }] } : result;
}
writeFileSync(new URL("src/validators.ts",root), '// Generated by scripts/generate-contract.mjs from docs/*-openapi.json.\nimport { v } from "convex/values";\n\n' + Object.entries(contracts).map(([name,s]) => `export const ${name} = ${validator(s)};\n\n`).join(""));
writeFileSync(new URL("src/component/lib/response_shapes.ts",root), '// Generated by scripts/generate-contract.mjs.\nimport type { ValidatorJSON } from "convex/values";\n' + ["search", "fetch"].map(name => `export const ${name}Shape: ValidatorJSON = ${JSON.stringify(shape(contracts[`${name}Response`]),null,2)};\n`).join(""));
console.log("Generated Convex validators and response decoders from the checked-in contracts.");
