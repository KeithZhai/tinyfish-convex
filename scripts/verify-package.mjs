import { mkdtempSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, join } from "node:path";
import { tmpdir } from "node:os";
import { execFileSync } from "node:child_process";
const dir = process.argv[2] ? resolve(process.argv[2]) : mkdtempSync(join(tmpdir(), "tinyfish-package-"));
mkdirSync(dir, { recursive: true });
execFileSync("npm", ["run", "build"], { stdio: "inherit" });
const packed = JSON.parse(execFileSync("npm", ["pack", "--json", "--ignore-scripts", "--pack-destination", dir], { encoding: "utf8" }))[0];
const forbidden = packed.files.filter(f => /(^|\/)(\.env[^/]*|\.convex|node_modules)(\/|$)/.test(f.path));
if (forbidden.length) throw new Error("Private development files included in package");
writeFileSync(join(dir, "package.json"), JSON.stringify({ private: true, type: "module" }));
execFileSync("npm", ["install", "--ignore-scripts", "--no-audit", "--no-fund", join(dir, packed.filename), "convex@1.46.0", "typescript@5.9.3", "vite@8", "convex-test@0.0.61", "vitest@4"], { cwd: dir, stdio: "inherit" });
writeFileSync(join(dir, "consumer.ts"), `import { TinyFish, makeAgentAPI, type SearchResponse, type FetchResponse, type AgentJob, type BrowserSession, type Profile } from "tinyfish-convex";
import component from "tinyfish-convex/convex.config.js";
import type { ComponentApi } from "tinyfish-convex/_generated/component.js";
import type { GenericActionCtx, GenericMutationCtx, GenericQueryCtx, GenericDataModel } from "convex/server";
declare const api: ComponentApi; declare const ctx: GenericActionCtx<GenericDataModel>;
declare const m: GenericMutationCtx<GenericDataModel>; declare const q: GenericQueryCtx<GenericDataModel>;
const tf = new TinyFish(api);
const search: Promise<SearchResponse> = tf.search(ctx, { query: "test", page: 0 });
const fetched: Promise<FetchResponse> = tf.fetch(ctx, { urls: ["https://docs.convex.dev"] });
const read: Promise<FetchResponse> = tf.read(ctx, { urls: ["https://docs.convex.dev"] });
const workflow = tf.research(ctx, {search:{query:"Convex"},maxSources:2});
const started: Promise<string> = tf.agent.start(m, {ownerId:"owner",idempotencyKey:"key",request:{url:"https://example.com",goal:"Read"}});
const job: Promise<AgentJob> = tf.agent.get(q, {ownerId:"owner",jobId:"id"});
const browser: Promise<BrowserSession> = tf.browser.create(ctx, {timeout_seconds:300});
const profile: Promise<Profile> = tf.profiles.create(ctx, {name:"Work"});
const mounted = makeAgentAPI(api,{authorize:async()=>"owner"});
// @ts-expect-error Profile use requires a boolean, not a string.
tf.agent.start(m,{ownerId:"owner",idempotencyKey:"key",request:{url:"https://example.com",goal:"Read",use_profile:"yes"}});
// @ts-expect-error Invalid format must fail at the consumer's type boundary.
tf.fetch(ctx, { urls: [], format: "xml" });
void component; void search; void fetched; void read; void workflow; void started; void job; void browser; void profile; void mounted;
`);
execFileSync(join(dir, "node_modules", ".bin", "tsc"), ["--noEmit", "--strict", "--skipLibCheck", "--target", "ES2022", "--module", "NodeNext", "--moduleResolution", "NodeNext", join(dir, "consumer.ts")], { cwd: dir, stdio: "inherit" });
execFileSync("node", ["--input-type=module", "-e", 'import { TinyFish } from "tinyfish-convex"; import config from "tinyfish-convex/convex.config.js"; if (!TinyFish || !config) throw new Error("Missing exports"); console.log("Isolated npm install, runtime exports and consumer TypeScript checks passed.");'], { cwd: dir, stdio: "inherit" });
writeFileSync(join(dir, "vitest.config.ts"), 'import { defineConfig } from "vitest/config"; export default defineConfig({test:{server:{deps:{inline:["tinyfish-convex"]}}}});');
writeFileSync(join(dir, "consumer.test.ts"), `import { expect, it, vi } from "vitest";
import { convexTest } from "convex-test";
import { defineSchema, makeFunctionReference } from "convex/server";
import { TinyFish, makeAgentAPI } from "tinyfish-convex";
import tinyfishTest from "tinyfish-convex/test";
it("uses the installed component test helper", async () => {
  const t = convexTest(defineSchema({}), { "./_generated/api.ts": async () => ({}), "./agent.ts": async () => makeAgentAPI(component, {authorize:async(ctx)=>{const identity=await ctx.auth.getUserIdentity();if(!identity)throw new Error("Sign in");return identity.tokenIdentifier;}}) });
  const component = tinyfishTest.register(t);
  vi.stubEnv("TINYFISH_API_KEY", "fake-key");
  vi.stubGlobal("fetch", async () => new Response(JSON.stringify({query:"test",results:[],total_results:0,page:0})));
  expect(await t.action(component.search.query, { query: "test" })).toEqual({query:"test",results:[],total_results:0,page:0});
  vi.stubGlobal("fetch", async () => new Response(JSON.stringify({results:[{url:"https://example.com",final_url:"https://example.com/",title:"Example",description:null,language:"en",format:"html",text:"<p>Read <code>API_KEY</code></p>",author:null,published_date:null}],errors:[]})));
  expect((await t.action(ctx=>new TinyFish(component).read(ctx,{urls:["https://example.com"]}))).results[0].text).toBe("Read " + String.fromCharCode(96) + "API_KEY" + String.fromCharCode(96));
  vi.useFakeTimers();
  const start=makeFunctionReference<"mutation">("agent:start");
  await expect(t.mutation(start,{idempotencyKey:"key",request:{url:"https://example.com",goal:"Read"}})).rejects.toThrow("Sign in");
  const authenticated=t.withIdentity({subject:"owner"});
  const jobId=await authenticated.mutation(start,{idempotencyKey:"key",request:{url:"https://example.com",goal:"Read"}});
  expect(await authenticated.query(makeFunctionReference<"query">("agent:get"),{jobId})).toMatchObject({status:"QUEUED"});
  await authenticated.mutation(makeFunctionReference<"mutation">("agent:cancel"),{jobId});
  await t.finishAllScheduledFunctions(vi.runAllTimers);
  vi.useRealTimers();
  vi.unstubAllEnvs(); vi.unstubAllGlobals();
});`);
execFileSync(join(dir, "node_modules", ".bin", "vitest"), ["run"], { cwd: dir, stdio: "inherit" });
console.log(`Verified ${packed.filename} (${packed.files.length} files).`);
